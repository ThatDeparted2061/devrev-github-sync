// Package sim simulates the two systems the sync connects: a GitHub repository
// (issues REST API + issues/pull_request webhooks) and a DevRev org
// (works.* API + work_created/work_updated webhooks).
//
// Every change, whether a user's (made through /admin) or the sync's (made
// through the APIs), produces the webhook the real system would send. The
// webhook then goes through chaos: some are dropped, some delivered twice,
// and all are delayed by a random amount, so they arrive out of order. The
// APIs also inject 429s (with Retry-After) and 5xx. An audit log of every
// write lets the checker tell real lost updates from unavoidable races.
package sim

import (
	"bytes"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"fmt"
	mrand "math/rand/v2"
	"net/http"
	"strings"
	"sync"
	"sync/atomic"
	"time"

	"github.com/ThatDeparted2061/devrev-github-sync/internal/devrev"
	"github.com/ThatDeparted2061/devrev-github-sync/internal/github"
)

// Config tunes the simulation.
type Config struct {
	Repo         string // owner/repo
	SyncURL      string // the sync's base URL; webhooks go to /webhooks/github and /webhooks/devrev
	GitHubSecret []byte
	DevRevSecret []byte

	Duplicate float64       // share of webhooks delivered twice
	Drop      float64       // share of webhooks never delivered
	MaxDelay  time.Duration // each delivery waits 0..MaxDelay, so deliveries overtake each other

	API429, API5xx float64       // per-call fault rates on both APIs
	APILatency     time.Duration // added to every API call (0..APILatency)

	// UniqueExternalRef makes works.create reject a second work item with the
	// same external_ref, as DevRev does. The benchmark turns it off to prove
	// the sync avoids duplicates on its own.
	UniqueExternalRef bool
}

type ghIssue struct {
	github.Issue
	merged bool
	events []ghEvent
}

type ghEvent struct {
	Event     string    `json:"event"`
	CreatedAt time.Time `json:"created_at"`
}

// Write is one change in the audit log.
type Write struct {
	At     time.Time `json:"at"`
	Side   string    `json:"side"`  // github | devrev
	Actor  string    `json:"actor"` // user | sync
	Key    string    `json:"key"`
	Field  string    `json:"field"` // create | title | status
	Status string    `json:"status,omitempty"`
	Title  string    `json:"title,omitempty"`
}

// Stats counts webhook deliveries.
type Stats struct {
	Webhooks   int64 `json:"webhooks"`   // generated by changes
	Delivered  int64 `json:"delivered"`  // HTTP deliveries attempted, duplicates included
	Duplicated int64 `json:"duplicated"` // extra copies sent
	Dropped    int64 `json:"dropped"`    // never sent
	Failed     int64 `json:"failed"`     // sent but not accepted (non-2xx or network error)
	InFlight   int64 `json:"in_flight"`  // scheduled, not yet sent
	API429     int64 `json:"api_429"`
	API5xx     int64 `json:"api_5xx"`
}

type Sim struct {
	cfg  Config
	http *http.Client

	mu     sync.Mutex
	last   time.Time
	issues map[int]*ghIssue
	next   int
	works  map[string]*devrev.Work
	nextW  int
	audit  []Write

	webhooks, delivered, duplicated, dropped, failed, inFlight, api429, api5xx atomic.Int64
}

func New(cfg Config) *Sim {
	return &Sim{cfg: cfg, issues: map[int]*ghIssue{}, works: map[string]*devrev.Work{}, next: 1, nextW: 1,
		http: &http.Client{Timeout: 10 * time.Second, Transport: &http.Transport{MaxIdleConnsPerHost: 256}}}
}

// now is a strictly increasing clock, so every write has a unique time.
func (s *Sim) now() time.Time {
	t := time.Now().UTC()
	if !t.After(s.last) {
		t = s.last.Add(time.Microsecond)
	}
	s.last = t
	return t
}

func (s *Sim) key(n int) string { return github.Key(s.cfg.Repo, n) }

func (s *Sim) Stats() Stats {
	return Stats{s.webhooks.Load(), s.delivered.Load(), s.duplicated.Load(), s.dropped.Load(), s.failed.Load(), s.inFlight.Load(), s.api429.Load(), s.api5xx.Load()}
}

// emit sends a webhook through chaos. Caller holds no lock.
func (s *Sim) emit(path string, headers map[string]string, body []byte) {
	s.webhooks.Add(1)
	if mrand.Float64() < s.cfg.Drop {
		s.dropped.Add(1)
		return
	}
	copies := 1
	if mrand.Float64() < s.cfg.Duplicate {
		copies = 2
		s.duplicated.Add(1)
	}
	for range copies {
		s.inFlight.Add(1)
		delay := time.Duration(mrand.Int64N(int64(s.cfg.MaxDelay) + 1))
		time.AfterFunc(delay, func() {
			defer s.inFlight.Add(-1)
			s.delivered.Add(1)
			req, _ := http.NewRequest(http.MethodPost, s.cfg.SyncURL+path, bytes.NewReader(body))
			req.Header.Set("Content-Type", "application/json")
			for k, v := range headers {
				req.Header.Set(k, v)
			}
			resp, err := s.http.Do(req)
			if err != nil {
				s.failed.Add(1)
				return
			}
			resp.Body.Close()
			if resp.StatusCode/100 != 2 {
				s.failed.Add(1)
			}
		})
	}
}

func uuid() string {
	b := make([]byte, 16)
	rand.Read(b)
	return hex.EncodeToString(b)
}

// githubWebhook builds and emits an issues/pull_request delivery for i.
func (s *Sim) githubWebhook(action string, i *ghIssue) {
	event, field := "issues", "issue"
	obj := map[string]any{"number": i.Number, "title": i.Title, "body": i.Body, "state": i.State,
		"state_reason": i.StateReason, "updated_at": i.UpdatedAt, "html_url": i.HTMLURL}
	if i.IsPR() {
		event, field = "pull_request", "pull_request"
		obj["merged"] = i.merged
	}
	body, _ := json.Marshal(map[string]any{"action": action, field: obj, "repository": map[string]string{"full_name": s.cfg.Repo}})
	headers := map[string]string{"X-GitHub-Event": event, "X-GitHub-Delivery": uuid()}
	if len(s.cfg.GitHubSecret) > 0 {
		headers["X-Hub-Signature-256"] = github.Sign(s.cfg.GitHubSecret, body)
	}
	go s.emit("/webhooks/github", headers, body)
}

func (s *Sim) devrevWebhook(typ string, w, old *devrev.Work) {
	ev := map[string]any{"id": "evt_" + uuid(), "type": typ, "timestamp": w.ModifiedDate, "webhook_id": "don:integration:dvrv-us-1:devo/sim:webhook/1"}
	switch typ {
	case "work_created":
		ev["work_created"] = map[string]any{"work": w}
	default:
		ev["work_updated"] = map[string]any{"work": w, "old_work": old}
	}
	body, _ := json.Marshal(ev)
	headers := map[string]string{}
	if len(s.cfg.DevRevSecret) > 0 {
		headers["X-DevRev-Signature"] = devrev.Sign(s.cfg.DevRevSecret, body)
	}
	go s.emit("/webhooks/devrev", headers, body)
}

// fault decides whether an API call fails; it also adds latency.
func (s *Sim) fault(w http.ResponseWriter) bool {
	if s.cfg.APILatency > 0 {
		time.Sleep(time.Duration(mrand.Int64N(int64(s.cfg.APILatency))))
	}
	switch x := mrand.Float64(); {
	case x < s.cfg.API429:
		s.api429.Add(1)
		w.Header().Set("Retry-After", "1")
		http.Error(w, `{"message":"rate limited"}`, http.StatusTooManyRequests)
		return true
	case x < s.cfg.API429+s.cfg.API5xx:
		s.api5xx.Add(1)
		http.Error(w, `{"message":"server error"}`, http.StatusBadGateway)
		return true
	}
	return false
}

func writeJSON(w http.ResponseWriter, code int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(code)
	json.NewEncoder(w).Encode(v)
}

func (s *Sim) Handler() http.Handler {
	mux := http.NewServeMux()
	// GitHub
	mux.HandleFunc("GET /repos/{owner}/{repo}/issues/{n}", s.ghGet)
	mux.HandleFunc("PATCH /repos/{owner}/{repo}/issues/{n}", s.ghPatch)
	mux.HandleFunc("GET /repos/{owner}/{repo}/issues", s.ghList)
	mux.HandleFunc("GET /repos/{owner}/{repo}/issues/{n}/events", s.ghEvents)
	// DevRev
	mux.HandleFunc("POST /works.create", s.dvCreate)
	mux.HandleFunc("GET /works.get", s.dvGet)
	mux.HandleFunc("GET /works.list", s.dvList)
	mux.HandleFunc("POST /works.update", s.dvUpdate)
	// Users and the checker
	mux.HandleFunc("POST /admin/github/issues", s.adminCreate)
	mux.HandleFunc("POST /admin/github/issues/{n}/{op}", s.adminGitHubOp)
	mux.HandleFunc("POST /admin/devrev/stage", s.adminStage)
	mux.HandleFunc("GET /admin/truth", s.truth)
	mux.HandleFunc("GET /admin/stats", func(w http.ResponseWriter, r *http.Request) { writeJSON(w, 200, s.Stats()) })
	return mux
}

func (s *Sim) checkRepo(w http.ResponseWriter, r *http.Request) bool {
	if r.PathValue("owner")+"/"+r.PathValue("repo") != s.cfg.Repo {
		http.Error(w, `{"message":"Not Found"}`, http.StatusNotFound)
		return false
	}
	return true
}

func (s *Sim) issue(w http.ResponseWriter, r *http.Request) *ghIssue {
	var n int
	fmt.Sscan(r.PathValue("n"), &n)
	i := s.issues[n]
	if i == nil {
		http.Error(w, `{"message":"Not Found"}`, http.StatusNotFound)
	}
	return i
}

func (s *Sim) ghGet(w http.ResponseWriter, r *http.Request) {
	if !s.checkRepo(w, r) || s.fault(w) {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if i := s.issue(w, r); i != nil {
		writeJSON(w, 200, i.Issue)
	}
}

func (s *Sim) ghEvents(w http.ResponseWriter, r *http.Request) {
	if !s.checkRepo(w, r) || s.fault(w) {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if i := s.issue(w, r); i != nil {
		writeJSON(w, 200, append([]ghEvent{}, i.events...))
	}
}

// ghPatch is the sync closing or reopening an issue.
func (s *Sim) ghPatch(w http.ResponseWriter, r *http.Request) {
	if !s.checkRepo(w, r) || s.fault(w) {
		return
	}
	var body struct {
		State       string `json:"state"`
		StateReason string `json:"state_reason"`
	}
	json.NewDecoder(r.Body).Decode(&body)
	s.mu.Lock()
	i := s.issue(w, r)
	if i == nil {
		s.mu.Unlock()
		return
	}
	action := s.setState(i, body.State, body.StateReason, false, "sync")
	out := i.Issue
	s.mu.Unlock()
	if action != "" {
		s.githubWebhook(action, i)
	}
	writeJSON(w, 200, out)
}

// setState changes an issue's state and returns the webhook action, or "" if
// nothing changed. Caller holds s.mu.
func (s *Sim) setState(i *ghIssue, state, reason string, merge bool, actor string) string {
	if state == i.State && (state == "open" || reason == i.StateReason) {
		return ""
	}
	t := s.now()
	action := "reopened"
	i.State, i.StateReason, i.UpdatedAt = state, "", t
	if state == "closed" {
		action = "closed"
		i.StateReason = reason
		if i.IsPR() {
			i.StateReason = ""
			if merge {
				i.merged = true
				i.PullRequest.MergedAt = &t
			}
		}
	} else if i.IsPR() && i.merged {
		return "" // a merged PR cannot be reopened
	}
	i.events = append(i.events, ghEvent{Event: action, CreatedAt: t})
	s.audit = append(s.audit, Write{At: t, Side: "github", Actor: actor, Key: s.key(i.Number), Field: "status", Status: ghStatus(i)})
	return action
}

func ghStatus(i *ghIssue) string {
	switch {
	case i.State == "open":
		return "open"
	case i.IsPR() && i.merged:
		return "closed:completed"
	case i.IsPR():
		return "closed:not_planned"
	case i.StateReason == "":
		return "closed:completed"
	}
	return "closed:" + i.StateReason
}

func (s *Sim) ghList(w http.ResponseWriter, r *http.Request) {
	if !s.checkRepo(w, r) || s.fault(w) {
		return
	}
	var page, per int
	fmt.Sscan(r.URL.Query().Get("page"), &page)
	fmt.Sscan(r.URL.Query().Get("per_page"), &per)
	page, per = max(page, 1), min(max(per, 1), 100)
	s.mu.Lock()
	all := make([]github.Issue, 0, len(s.issues))
	for n := 1; n < s.next; n++ { // stable order; sort by updated is not needed by the sync
		all = append(all, s.issues[n].Issue)
	}
	s.mu.Unlock()
	lo := min((page-1)*per, len(all))
	writeJSON(w, 200, all[lo:min(lo+per, len(all))])
}

func (s *Sim) dvCreate(w http.ResponseWriter, r *http.Request) {
	if s.fault(w) {
		return
	}
	var body struct {
		Type          string       `json:"type"`
		Title         string       `json:"title"`
		Body          string       `json:"body"`
		AppliesToPart string       `json:"applies_to_part"`
		OwnedBy       []string     `json:"owned_by"`
		ExternalRef   string       `json:"external_ref"`
		Stage         devrev.Stage `json:"stage"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil || body.Type == "" || body.Title == "" || body.AppliesToPart == "" || len(body.OwnedBy) == 0 {
		writeJSON(w, 400, map[string]string{"type": "bad_request", "message": "type, title, applies_to_part and owned_by are required"})
		return
	}
	s.mu.Lock()
	if s.cfg.UniqueExternalRef && body.ExternalRef != "" {
		for _, x := range s.works {
			if x.ExternalRef == body.ExternalRef {
				s.mu.Unlock()
				writeJSON(w, 409, map[string]string{"type": "conflict", "message": "external_ref already exists"})
				return
			}
		}
	}
	n := s.nextW
	s.nextW++
	wk := &devrev.Work{ID: fmt.Sprintf("don:core:dvrv-us-1:devo/sim:issue/%d", n), DisplayID: fmt.Sprintf("ISS-%d", n), Type: body.Type,
		Title: body.Title, Body: body.Body, Stage: devrev.Stage{Name: cmpOr(body.Stage.Name, "triage")}, ExternalRef: body.ExternalRef, ModifiedDate: s.now()}
	s.works[wk.ID] = wk
	s.audit = append(s.audit, Write{At: wk.ModifiedDate, Side: "devrev", Actor: "sync", Key: strings.TrimPrefix(body.ExternalRef, "github:"), Field: "create", Status: dvStatus(wk.Stage.Name), Title: wk.Title})
	out := *wk
	s.mu.Unlock()
	s.devrevWebhook("work_created", &out, nil)
	writeJSON(w, 201, map[string]any{"work": out})
}

func cmpOr(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

func dvStatus(stage string) string {
	switch stage {
	case "completed":
		return "closed:completed"
	case "wont_fix":
		return "closed:not_planned"
	case "duplicate":
		return "closed:duplicate"
	}
	return "open"
}

func (s *Sim) dvGet(w http.ResponseWriter, r *http.Request) {
	if s.fault(w) {
		return
	}
	s.mu.Lock()
	wk := s.works[r.URL.Query().Get("id")]
	var out devrev.Work
	if wk != nil {
		out = *wk
	}
	s.mu.Unlock()
	if wk == nil {
		writeJSON(w, 404, map[string]string{"type": "not_found", "message": "work not found"})
		return
	}
	writeJSON(w, 200, map[string]any{"work": out})
}

func (s *Sim) dvList(w http.ResponseWriter, r *http.Request) {
	if s.fault(w) {
		return
	}
	q := r.URL.Query()
	ref := q.Get("external_ref")
	var cursor int
	fmt.Sscan(q.Get("cursor"), &cursor)
	s.mu.Lock()
	var out []devrev.Work
	for n := 1; n < s.nextW; n++ {
		wk := s.works[fmt.Sprintf("don:core:dvrv-us-1:devo/sim:issue/%d", n)]
		if wk != nil && (ref == "" || wk.ExternalRef == ref) {
			out = append(out, *wk)
		}
	}
	s.mu.Unlock()
	if ref != "" {
		writeJSON(w, 200, map[string]any{"works": out})
		return
	}
	end := min(cursor+100, len(out))
	next := ""
	if end < len(out) {
		next = fmt.Sprint(end)
	}
	writeJSON(w, 200, map[string]any{"works": out[min(cursor, len(out)):end], "next_cursor": next})
}

// dvUpdate is the sync updating a work item.
func (s *Sim) dvUpdate(w http.ResponseWriter, r *http.Request) {
	if s.fault(w) {
		return
	}
	var body struct {
		ID    string        `json:"id"`
		Title string        `json:"title"`
		Body  string        `json:"body"`
		Stage *devrev.Stage `json:"stage"`
	}
	json.NewDecoder(r.Body).Decode(&body)
	s.mu.Lock()
	wk := s.works[body.ID]
	if wk == nil {
		s.mu.Unlock()
		writeJSON(w, 404, map[string]string{"type": "not_found", "message": "work not found"})
		return
	}
	old := *wk
	changed := false
	if body.Title != "" && body.Title != wk.Title {
		wk.Title, changed = body.Title, true
	}
	if body.Body != "" && body.Body != wk.Body {
		wk.Body, changed = body.Body, true
	}
	statusChanged := body.Stage != nil && body.Stage.Name != "" && body.Stage.Name != wk.Stage.Name
	if statusChanged {
		wk.Stage, changed = *body.Stage, true
	}
	if changed {
		wk.ModifiedDate = s.now()
		if body.Title != "" && old.Title != wk.Title {
			s.audit = append(s.audit, Write{At: wk.ModifiedDate, Side: "devrev", Actor: "sync", Key: strings.TrimPrefix(wk.ExternalRef, "github:"), Field: "title", Title: wk.Title})
		}
		if statusChanged && dvStatus(old.Stage.Name) != dvStatus(wk.Stage.Name) {
			s.audit = append(s.audit, Write{At: wk.ModifiedDate, Side: "devrev", Actor: "sync", Key: strings.TrimPrefix(wk.ExternalRef, "github:"), Field: "status", Status: dvStatus(wk.Stage.Name)})
		}
	}
	out := *wk
	s.mu.Unlock()
	if changed {
		s.devrevWebhook("work_updated", &out, &old)
	}
	writeJSON(w, 200, map[string]any{"work": out})
}
